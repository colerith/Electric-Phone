/** The model dialect is a runtime constraint; editable direction lives in the Fish preset. */
export function fishModelRules(model = ''): string {
  const id = model.trim().toLowerCase();
  if (/^s2(?:[.-]|$)/.test(id))
    return '当前 Fish 模型使用 S2 系列行内语法：用半角方括号 [标签]，允许与正文同语言的自然描述；不要使用 S1 小括号、MiniMax 停顿符、SSML 或多说话人控制符。';
  if (id === 's1')
    return '当前 Fish 模型为 S1：不使用 S2 自由描述方括号。需要情绪时只在句首少量使用 (happy)、(sad)、(angry)、(excited) 英文小括号标签，后接完整台词；不确定时保留自然口语，不添加标签。';
  return '当前 Fish 模型的行内标签语法尚未确认（包括 Drama 3 或自定义模型）：本轮使用无标签自然口语，不套用 S2、S1、MiniMax 或 ElevenLabs 语法。';
}

